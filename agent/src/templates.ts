import type { AppSpec } from './app-spec.ts'

/** Project name for an app's compose stack (also its container name prefix). */
export const projectName = (name: string) => `spotcraft-app-${name}`

/** Caddy reaches each app by this alias on the shared edge network. */
export const upstreamAlias = (name: string) => `app-${name}`

/** Compose interpolates `$VAR` even in values; `$$` is a literal dollar sign. */
const escapeCompose = (value: string) => value.replaceAll('$', '$$$$')

/**
 * The app's compose file. Written as JSON (valid YAML), so values never need YAML escaping.
 * Hardened by default: no capabilities, no privilege escalation, resource limits.
 */
export function renderCompose(app: AppSpec): string {
  const env = Object.fromEntries(
    Object.entries(app.env).map(([key, value]) => [key, escapeCompose(value)]),
  )
  const service: Record<string, unknown> = {
    image: `${app.image}:${app.tag}`,
    restart: 'unless-stopped',
    environment: env,
    networks: { edge: { aliases: [upstreamAlias(app.name)] } },
    cap_drop: ['ALL'],
    security_opt: ['no-new-privileges:true'],
    mem_limit: app.memory,
    cpus: app.cpus,
    pids_limit: 256,
    stop_grace_period: '30s',
    logging: { driver: 'json-file', options: { 'max-size': '10m', 'max-file': '3' } },
  }
  if (app.readOnly) {
    service.read_only = true
    service.tmpfs = ['/tmp:size=64m,noexec,nosuid,nodev']
  }
  const compose = {
    name: projectName(app.name),
    services: { [app.name]: service },
    networks: { edge: { name: 'spotcraft-edge', external: true } },
  }
  return `${JSON.stringify(compose, null, 2)}\n`
}

/**
 * Whether `www.<domain>` should redirect to the domain: only for a registrable root like
 * `tagtape.app`. A subdomain (`app.example.com`) gets no `www.` site, which would otherwise
 * make Caddy request a certificate for a name nobody points at the server.
 */
export const wantsWwwRedirect = (domain: string) => domain.split('.').length === 2

/** The app's Caddy site block, imported by the apps server's main Caddyfile. */
export function renderSite(app: AppSpec): string {
  const www = wantsWwwRedirect(app.domain)
    ? `
www.${app.domain} {
\tredir https://${app.domain}{uri} permanent
}
`
    : ''
  return `# Generated by the Spotcraft agent for "${app.name}"; changes are overwritten on deploy.
${app.domain} {
\tencode zstd gzip
\theader {
\t\tStrict-Transport-Security "max-age=31536000; includeSubDomains"
\t\tX-Content-Type-Options "nosniff"
\t\tReferrer-Policy "strict-origin-when-cross-origin"
\t\t-Server
\t}
\treverse_proxy ${upstreamAlias(app.name)}:${app.port}
}
${www}`
}
